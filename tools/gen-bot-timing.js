// Learns the bot's aiming table: for each flipper and shot, which
// release-to-flip delays (from a cradled ball) make that shot.
// Writes src/game/bot-timing.js. Usage: node tools/gen-bot-timing.js
const fs = require('fs');
const path = require('path');
const { cradleShot } = require('../tests/table.test.js');
const out = { L: {}, R: {}, U: {} };
for (const fid of ['L', 'R', 'U']) {
  for (let d = 0; d <= 0.6; d += 0.002) {
    const r = cradleShot(fid, d);
    if (['drain', 'none', 'nocradle'].includes(r.shot)) continue;
    // keep only delays that also work 2 ms either side (robust to timing noise)
    const a = cradleShot(fid, d - 0.002).shot, b = cradleShot(fid, d + 0.002).shot;
    const robust = a === r.shot || b === r.shot;
    if (!robust) continue;
    (out[fid][r.shot] = out[fid][r.shot] || []).push(+d.toFixed(3));
  }
}
const src = `// Generated by tools/gen-bot-timing.js: cradle release-to-flip delays (s) that make each shot.
(function (NN) {
  'use strict';
  NN.BOT_TIMING = ${JSON.stringify(out)};
})(globalThis.NN || (globalThis.NN = {}));
`;
fs.writeFileSync(path.join(__dirname, '..', 'src/game/bot-timing.js'), src);
for (const f in out) console.log(f, Object.entries(out[f]).map(([k, v]) => k + ':' + v.length).join(' '));
