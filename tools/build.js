// Bundles src/ into one self-contained index.html (plus sw.js for the
// installable version). No dependencies: node tools/build.js
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.join(__dirname, '..');
const manifest = require('./manifest');
const pkg = require(path.join(root, 'package.json'));

const files = manifest.core.concat(manifest.browser);
let js = '';
for (const f of files) {
  const src = fs.readFileSync(path.join(root, f), 'utf8');
  if (src.includes('</script')) throw new Error(f + ' contains </script');
  js += `\n/* ---- ${f} ---- */\n` + src;
}
const tpl = fs.readFileSync(path.join(root, 'src/index.template.html'), 'utf8');
const hash = crypto.createHash('sha1').update(js + tpl).digest('hex').slice(0, 8);
const version = `v${pkg.version}-${hash}`;
const html = tpl
  .replace('{{VERSION}}', version)
  .replace('<!--APPLE_ICON-->', '')
  .replace('{{SCRIPT}}', () => js.replace(/__BUILD_VERSION__/g, version));
fs.writeFileSync(path.join(root, 'index.html'), html);

// service worker: cache-first, versioned by the build hash
const sw = `// NEON NEBULA service worker (generated by tools/build.js)
const CACHE = 'neon-nebula-${version}';
const FILES = ['./', './index.html', './manifest.webmanifest', './icon-192.png', './icon-512.png', './apple-touch-icon.png'];
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
    const copy = res.clone();
    if (res.ok && new URL(e.request.url).origin === location.origin) caches.open(CACHE).then((c) => c.put(e.request, copy));
    return res;
  }).catch(() => caches.match('./index.html'))));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`built index.html ${(html.length / 1024).toFixed(0)} KB, ${files.length} source files, ${version}`);
